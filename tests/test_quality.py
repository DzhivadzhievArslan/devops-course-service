"""Проверка качества модели: конвейер красный, если точность упала ниже порога.

Порог 0,85 взят по замеру 23.11.2026: на отложенной части данных (25 %, разбиение
random_state=42) точность 0,925; на 20 других разбиениях — от 0,775 до 0,975, в среднем 0,889.
Если поменять данные или параметры и точность упадёт, тест не даст слить такие изменения.
"""

MIN_ACCURACY = 0.85


def test_model_accuracy(trained_model):
    assert trained_model.accuracy >= MIN_ACCURACY, (
        f"Точность {trained_model.accuracy:.3f} ниже порога {MIN_ACCURACY}"
    )
